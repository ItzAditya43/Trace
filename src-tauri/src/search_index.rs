/// A page or Control section's name as shown in the sidebar, for result details.
pub fn place(page: &str, section: Option<&str>) -> String {
    let name = match page {
        "live" => "Overview",
        "memory" => "Memory",
        "activity" => "Activity",
        "hardware" => "Hardware",
        "health" => "Health",
        "history" => "History",
        "logs" => "Logs",
        "diagnose" => "Investigate",
        "projects" => "Projects",
        "tweaks" => "Tweaks",
        _ => "Control",
    };
    match section {
        Some("apps") => "Control › Apps & Processes".into(),
        Some("power") => "Control › Power & Memory".into(),
        Some("network") => "Control › Network".into(),
        Some("devices") => "Control › Display & Devices".into(),
        Some("services") => "Control › Services".into(),
        Some("automation") => "Control › Automation".into(),
        Some("packages") => "Control › Packages & Cleanup".into(),
        _ => name.into(),
    }
}
